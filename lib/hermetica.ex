defmodule Hermetica do
  @moduledoc """
  Hermetica API client. Generated by scripts/gen-sdks.mjs; the operations are in Hermetica.Api.

      hm = Hermetica.new("hm_sk_...", "https://api.example.com")
      {:ok, page} = Hermetica.Api.get_v1_profiles(hm, query: %{limit: 25})
  """

  defmodule Error do
    @moduledoc "Any non-2xx answer, or a network error (status 0)."
    defexception [:status, :code, :message, :details]
    @type t :: %__MODULE__{status: non_neg_integer(), code: String.t(), message: String.t(), details: term()}
    @impl true
    def message(%{status: s, code: c, message: m}), do: "#{s} #{c}: #{m}"
  end

  defstruct [:api_key, :base_url, workspace_id: nil, max_retries: 3, req_options: []]
  @type t :: %__MODULE__{api_key: String.t(), base_url: String.t(), workspace_id: String.t() | nil, max_retries: non_neg_integer(), req_options: keyword()}

  @doc "Options: workspace_id (sent as X-Workspace-Id), max_retries (default 3; 0 turns retries off), req_options (passed to Req)."
  @spec new(String.t(), String.t(), keyword()) :: t()
  def new(api_key, base_url, opts \\ []) do
    struct!(__MODULE__, [api_key: api_key, base_url: String.trim_trailing(base_url, "/")] ++ opts)
  end

  @doc "Runs one operation. Options: path, query, body, idempotency_key."
  @spec request(t(), String.t(), String.t(), keyword()) :: {:ok, term()} | {:error, Error.t()}
  def request(%__MODULE__{} = c, method, path, opts \\ []) do
    params = Map.new(opts[:path] || %{}, fn {k, v} -> {to_string(k), v} end)

    with {:ok, resolved} <- resolve(path, params) do
      # A retry with the same key never repeats the action: every attempt of a non-GET carries it.
      key = if method == "GET", do: nil, else: opts[:idempotency_key] || uuid()

      headers =
        [{"authorization", "Bearer " <> c.api_key}, {"accept", "application/json"}] ++
          if(c.workspace_id, do: [{"x-workspace-id", c.workspace_id}], else: []) ++
          if(key, do: [{"idempotency-key", key}], else: [])

      req = [method: method |> String.downcase() |> String.to_atom(), url: c.base_url <> resolved, headers: headers, retry: false]
      req = if q = opts[:query], do: Keyword.put(req, :params, Enum.reject(q, fn {_, v} -> is_nil(v) end)), else: req
      req = if Keyword.has_key?(opts, :body), do: Keyword.put(req, :json, opts[:body]), else: req
      req = Keyword.merge(req, c.req_options)

      attempt(c, req, 0)
    end
  end

  defp attempt(c, req, n) do
    case Req.request(req) do
      {:ok, %Req.Response{status: s} = res} when (s == 429 or s >= 500) and n < c.max_retries ->
        Process.sleep(retry_after(res) || backoff(n))
        attempt(c, req, n + 1)

      {:ok, %Req.Response{status: s, body: body}} when s < 300 ->
        {:ok, if(body == "", do: nil, else: body)}

      {:ok, %Req.Response{status: s, body: body}} ->
        e = if is_map(body), do: body["error"] || %{}, else: %{}
        {:error, %Error{status: s, code: e["code"] || "http_error", message: e["message"] || to_string(inspect_body(body)), details: e["details"]}}

      {:error, _} when n < c.max_retries ->
        Process.sleep(backoff(n))
        attempt(c, req, n + 1)

      {:error, e} ->
        {:error, %Error{status: 0, code: "network_error", message: Exception.message(e), details: nil}}
    end
  end

  @doc "Every item of a list operation (a Hermetica.Api function), following nextCursor."
  @spec list_all(t(), (t(), keyword() -> {:ok, term()} | {:error, Error.t()}), keyword()) :: {:ok, list()} | {:error, Error.t()}
  def list_all(c, fun, opts \\ []), do: pages(c, fun, opts, [])

  defp pages(c, fun, opts, acc) do
    with {:ok, page} <- fun.(c, opts) do
      acc = acc ++ ((is_map(page) && page["items"]) || [])

      case is_map(page) && page["nextCursor"] do
        next when is_binary(next) and next != "" -> pages(c, fun, Keyword.update(opts, :query, %{"cursor" => next}, &Map.put(Map.new(&1), "cursor", next)), acc)
        _ -> {:ok, acc}
      end
    end
  end

  defp resolve(path, params) do
    missing = Regex.scan(~r/\{(\w+)\}/, path) |> Enum.map(&List.last/1) |> Enum.reject(&Map.has_key?(params, &1))

    if missing == [] do
      {:ok, Regex.replace(~r/\{(\w+)\}/, path, fn _, name -> URI.encode(to_string(params[name]), &URI.char_unreserved?/1) end)}
    else
      {:error, %Error{status: 0, code: "invalid", message: "missing path param " <> Enum.join(missing, ", "), details: nil}}
    end
  end

  # Full jitter: a random wait up to 250ms * 2^n, capped at 8s.
  defp backoff(n), do: :rand.uniform(if(n < 5, do: Bitwise.bsl(250, n), else: 8000)) - 1

  # Retry-After in delta-seconds; an HTTP-date (rare from this API) falls back to the backoff.
  defp retry_after(res) do
    with [v | _] <- Req.Response.get_header(res, "retry-after"), {secs, ""} <- Float.parse(String.trim(v)), true <- secs >= 0 and secs < 1.0e6 do
      round(secs * 1000)
    else
      _ -> nil
    end
  end

  defp inspect_body(b) when is_binary(b), do: String.trim(b)
  defp inspect_body(b), do: inspect(b)

  defp uuid do
    <<a::48, _::4, b::12, _::2, c::62>> = :crypto.strong_rand_bytes(16)
    <<x::128>> = <<a::48, 4::4, b::12, 2::2, c::62>>
    hex = x |> Integer.to_string(16) |> String.pad_leading(32, "0") |> String.downcase()
    Enum.join([binary_part(hex, 0, 8), binary_part(hex, 8, 4), binary_part(hex, 12, 4), binary_part(hex, 16, 4), binary_part(hex, 20, 12)], "-")
  end
end
